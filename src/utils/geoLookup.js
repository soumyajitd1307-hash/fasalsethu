/**
 * Resolves a manual location string to { lat, lng, displayName }.
 * Uses local fast dictionary first, then falls back to Google Maps Geocoder if loaded.
 */
export async function resolveLocationCoords(query) {
  if (!query || typeof query !== 'string') {
    return { lat: 20.20, lng: 73.83, name: 'Dindori, Nashik' }
  }

  const clean = query.trim().toLowerCase()

  // 1. Direct dictionary lookup
  for (const [key, hub] of Object.entries(INDIAN_AGRI_HUBS)) {
    if (clean.includes(key) || key.includes(clean)) {
      return { lat: hub.lat, lng: hub.lng, name: hub.name }
    }
  }

  // 2. Try Google Maps Geocoder if Google Maps JS API is available
  if (typeof window !== 'undefined' && window.google?.maps?.Geocoder) {
    try {
      const geocoder = new window.google.maps.Geocoder()
      const res = await new Promise((resolve) => {
        geocoder.geocode({ address: query + ', India' }, (results, status) => {
          if (status === 'OK' && results && results[0]) {
            resolve({
              lat: results[0].geometry.location.lat(),
              lng: results[0].geometry.location.lng(),
              name: results[0].formatted_address,
            })
          } else {
            resolve(null)
          }
        })
      })
      if (res) return res
    } catch (e) {
      console.warn('Google Geocoder lookup failed:', e)
    }
  }

  // Default to Nashik farm hub if unknown
  return { lat: 20.20, lng: 73.83, name: query }
}
